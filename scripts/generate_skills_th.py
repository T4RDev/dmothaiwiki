def transliterate_word(w: str) -> str:
    low = w.lower()
    if low in WORDS_TH:
        return WORDS_TH[low]
    # Check if word ends with 's like Heaven's -> เฮฟเวนส์, Agumon's -> อากูมอนส์
    if low.endswith("'s"):
        base = low[:-2]
        if base in WORDS_TH:
            return WORDS_TH[base] + "ส์"
    # Check if word ends with s like blades -> เบลดส์
    if low.endswith("s") and len(low) > 3:
        base = low[:-1]
        if base in WORDS_TH:
            return WORDS_TH[base] + "ส์"
    return w

def transliterate_skill(skill_name: str) -> str:
    s = skill_name.strip()
    if s in PHRASE_OVERRIDES:
        return PHRASE_OVERRIDES[s]

    # Handle tokens preserving punctuation and whitespace
    tokens = re.split(r'(\s+|[\(\)\-\,\.\:\/\&])', s)
    out = []
    for t in tokens:
        if not t or re.match(r'^\s+$', t):
            out.append(t)
        elif t in '()-,.:/&':
            out.append(t)
        else:
            out.append(transliterate_word(t))
    res = ''.join(out)
    # clean extra spaces around punctuation if any
    res = re.sub(r'\s+', ' ', res).strip()
    return res

def main():
    root = Path(__file__).resolve().parent.parent
    skills_file = root / "web" / "all_skills_list.json"
    if not skills_file.exists():
        print("Missing all_skills_list.json")
        return

    skills = json.loads(skills_file.read_text(encoding="utf-8"))
    out_dict = {}

    missing_words = set()
    for s in skills:
        th = transliterate_skill(s)
        out_dict[s] = th
        # Check if any English letters remain
        remain = re.findall(r'[a-zA-Z]+', th)
        for r in remain:
            if r.lower() not in WORDS_TH:
                missing_words.add(r.lower())

    out_path = root / "web" / "i18n" / "th_skills.json"
    out_path.write_text(json.dumps(out_dict, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Generated {len(out_dict)} translated skills into {out_path}!")
    if missing_words:
        print(f"Remaining unmapped words ({len(missing_words)}):", sorted(list(missing_words)))
    else:
        print("100% OF ALL WORDS ARE FULLY TRANSLATED INTO THAI KARAOKE!")

if __name__ == "__main__":
    main()
